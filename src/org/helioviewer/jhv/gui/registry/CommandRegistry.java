package org.helioviewer.jhv.gui.registry;

import java.awt.event.ActionEvent;
import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.Collection;
import java.util.Collections;
import java.util.LinkedHashMap;
import java.util.Map;

import javax.annotation.Nullable;

import org.helioviewer.jhv.app.Commands;
import org.helioviewer.jhv.app.Platform;
import org.helioviewer.jhv.gui.ActionCatalog;
import org.helioviewer.jhv.gui.MainFrame;
import org.helioviewer.jhv.time.JHVTime;

import org.json.JSONArray;
import org.json.JSONObject;

import static org.helioviewer.jhv.gui.registry.CommandSpec.Effect;

/**
 * Every command an outside caller can run, by id. It is built from two sources:
 * <ul>
 * <li>every {@link ActionCatalog} entry, as a command with no arguments whose handler performs the
 * action (the menu item, the toolbar button and the search result run the same Action);</li>
 * <li>commands with typed arguments, declared in {@link #registerParameterised()}, that call
 * {@link Commands} (the layer the SAMP handlers call too).</li>
 * </ul>
 * The registry is the planned HelioFITS Studio method table: docs/commands.json is its machine
 * readable form (an MCP tools list), regenerated by {@code main} and held current by RegistryCheck.
 * An MCP server, API or command line wraps {@link Dispatch#invoke} and publishes that file; it adds
 * no verbs of its own.
 */
public final class CommandRegistry {

    private static final JSONObject NO_ARGS = new JSONObject("{\"type\":\"object\",\"properties\":{},\"additionalProperties\":false}");
    private static final JSONObject EMPTY_RESULT = new JSONObject("{\"type\":\"object\",\"properties\":{}}");

    /**
     * What a catalogued command does to the user's work. Not listed means UI (opens or shows part of
     * the interface). This is the author's judgement, to be reviewed; a front end uses it to decide
     * what to confirm.
     */
    static final Map<String, Effect> EFFECTS = Map.ofEntries(
            Map.entry("newSession", Effect.DESTRUCTIVE), Map.entry("openSession", Effect.DESTRUCTIVE),
            Map.entry("closeWindow", Effect.DESTRUCTIVE), Map.entry("quit", Effect.DESTRUCTIVE),
            Map.entry("revertToSaved", Effect.DESTRUCTIVE), Map.entry("clearRecents", Effect.WRITE),
            Map.entry("clearAnnotations", Effect.DESTRUCTIVE), Map.entry("clearDefaultSession", Effect.WRITE),
            Map.entry("setDefaultSession", Effect.WRITE), Map.entry("saveSession", Effect.WRITE),
            Map.entry("saveSessionAs", Effect.WRITE), Map.entry("exportSessionWithData", Effect.WRITE),
            Map.entry("undo", Effect.WRITE), Map.entry("redo", Effect.WRITE), Map.entry("paste", Effect.WRITE),
            Map.entry("reloadSources", Effect.WRITE), Map.entry("duplicateLayer", Effect.WRITE),
            Map.entry("zoomIn", Effect.WRITE), Map.entry("zoomOut", Effect.WRITE), Map.entry("zoomFit", Effect.WRITE),
            Map.entry("zoomOne", Effect.WRITE), Map.entry("resetCamera", Effect.WRITE), Map.entry("resetAxis", Effect.WRITE),
            Map.entry("rotate90X", Effect.WRITE), Map.entry("rotate90Y", Effect.WRITE), Map.entry("rotate90Z", Effect.WRITE),
            Map.entry("playPause", Effect.WRITE), Map.entry("previousFrame", Effect.WRITE), Map.entry("nextFrame", Effect.WRITE),
            Map.entry("record", Effect.WRITE), Map.entry("trimStart", Effect.WRITE), Map.entry("trimEnd", Effect.WRITE),
            Map.entry("trimReset", Effect.WRITE), Map.entry("copyFrame", Effect.WRITE), Map.entry("copyProvenance", Effect.WRITE),
            Map.entry("quickShare", Effect.WRITE), Map.entry("shareScene", Effect.WRITE), Map.entry("sendToPython", Effect.WRITE),
            Map.entry("openDemo", Effect.DESTRUCTIVE), Map.entry("punchLatest", Effect.WRITE));

    private static final Map<String, CommandSpec> specs = new LinkedHashMap<>(); // the map is the only state (guards.py ratchet)

    /** Builds every spec once. Idempotent; get() and all() call it. */
    public static synchronized void register() {
        if (!specs.isEmpty())
            return;
        for (ActionCatalog.Entry e : ActionCatalog.all()) {
            String id = e.id();
            add(new CommandSpec(id, e.description(), EFFECTS.getOrDefault(id, Effect.UI), NO_ARGS, EMPTY_RESULT, args -> {
                Object source = MainFrame.get() != null ? MainFrame.get() : CommandRegistry.class;
                e.action().actionPerformed(new ActionEvent(source, ActionEvent.ACTION_PERFORMED, id));
                return new JSONObject();
            }, () -> e.action().isEnabled()));
        }
        registerParameterised();
        registerIntrospection();
    }

    /**
     * Commands with arguments. Each calls {@link Commands}, the same layer the SAMP handlers use,
     * so a value rejected here is rejected the same way there. Later work packages (the view verbs
     * of the parameter study, the method table) append one add() each.
     */
    private static void registerParameterised() {
        add(new CommandSpec("seekFrame", "Show the movie frame with this number (0 is the first)", Effect.WRITE,
                object("{\"frame\":{\"type\":\"integer\",\"minimum\":0,\"description\":\"Frame number, 0 is the first frame\"}}", "frame"),
                EMPTY_RESULT, args -> {
                    Commands.seekFrame(args.getInt("frame"));
                    return new JSONObject();
                }, () -> true));
        add(new CommandSpec("seekTime", "Move the movie to the frame nearest this time", Effect.WRITE,
                object("{\"time\":{\"type\":\"string\",\"description\":\"UTC time, for example 2012-08-31T19:30:00\"}}", "time"),
                EMPTY_RESULT, args -> {
                    JHVTime time;
                    try {
                        time = new JHVTime(args.getString("time"));
                    } catch (java.time.DateTimeException e) {
                        throw new IllegalArgumentException("'" + args.getString("time") + "' is not a UTC time such as 2012-08-31T19:30:00");
                    }
                    Commands.seekTime(time);
                    return new JSONObject();
                }, () -> true));
        add(new CommandSpec("rotateView90", "Rotate the view 90 degrees about one axis of the screen", Effect.WRITE,
                object("{\"axis\":{\"type\":\"string\",\"enum\":[\"X\",\"Y\",\"Z\"],\"description\":\"The axis to rotate about\"}}", "axis"),
                EMPTY_RESULT, args -> {
                    Commands.rotateView90(args.getString("axis"));
                    return new JSONObject();
                }, () -> true));
    }

    /**
     * The two read commands an assistant or a script starts from: what can be run, and what is known
     * about one command or control (the lookup behind "how do I...", from ControlRegistry).
     */
    private static void registerIntrospection() {
        add(new CommandSpec("listCommands", "List every command: its id, what it does and what it changes", Effect.READ, NO_ARGS,
                o("{\"type\":\"object\",\"properties\":{\"commands\":{\"type\":\"array\"}}}"), args -> {
                    JSONArray list = new JSONArray();
                    for (CommandSpec c : all())
                        list.put(new JSONObject().put("id", c.id()).put("description", c.description())
                                .put("effect", c.effect().name().toLowerCase(java.util.Locale.ROOT)).put("needsArguments", c.needsArguments()));
                    return new JSONObject().put("commands", list);
                }, () -> true));
        add(new CommandSpec("describeControl", "Say what a command or control is, where it is, its shortcut, and which tours and tips show it", Effect.READ,
                object("{\"id\":{\"type\":\"string\",\"description\":\"A command id or a control id, as listCommands or Help > Search Controls shows\"}}", "id"),
                o("{\"type\":\"object\",\"properties\":{\"id\":{\"type\":\"string\"},\"kind\":{\"type\":\"string\"},\"title\":{\"type\":\"string\"},"
                        + "\"where\":{\"type\":\"string\"},\"tooltip\":{\"type\":\"string\"},\"shortcut\":{\"type\":\"string\"},"
                        + "\"tours\":{\"type\":\"array\"},\"tips\":{\"type\":\"array\"}}}"), args -> {
                    ControlRegistry.Entry e = ControlRegistry.get(args.getString("id"));
                    if (e == null)
                        throw new IllegalArgumentException("no command or control '" + args.getString("id") + "'");
                    JSONObject out = new JSONObject().put("id", e.id()).put("kind", e.kind().name().toLowerCase(java.util.Locale.ROOT))
                            .put("title", e.title()).put("where", e.where()).put("tooltip", e.tooltip()).put("shortcut", e.shortcut())
                            .put("tours", new JSONArray(e.tours())).put("tips", new JSONArray(e.tips()));
                    if (e.doc() != null)
                        out.put("doc", e.doc());
                    return out;
                }, () -> true));
    }

    private static JSONObject o(String json) {
        return new JSONObject(json);
    }

    private static JSONObject object(String properties, String... required) {
        JSONObject o = new JSONObject();
        o.put("type", "object");
        o.put("properties", new JSONObject(properties));
        o.put("required", new JSONArray(required));
        o.put("additionalProperties", false);
        return o;
    }

    private static void add(CommandSpec spec) {
        if (specs.containsKey(spec.id()))
            throw new IllegalStateException("duplicate command id " + spec.id());
        specs.put(spec.id(), spec);
    }

    @Nullable
    public static synchronized CommandSpec get(String id) {
        register();
        return specs.get(id);
    }

    /** Every command, in registration order: the catalogued actions, then the parameterised ones. */
    public static synchronized Collection<CommandSpec> all() {
        register();
        return Collections.unmodifiableCollection(specs.values());
    }

    /**
     * The registry as an MCP tools list: name, description, inputSchema, outputSchema and the
     * read-only and destructive hints. Platform independent, so the file in docs/ is the same from
     * any computer; menu paths and shortcuts, which differ by platform, are not in it.
     */
    public static JSONObject manifest() {
        JSONArray tools = new JSONArray();
        for (CommandSpec c : all()) {
            JSONObject t = new JSONObject();
            t.put("name", c.id());
            t.put("description", c.description());
            t.put("inputSchema", c.input());
            t.put("outputSchema", c.output());
            JSONObject hints = new JSONObject();
            hints.put("readOnlyHint", c.effect() == Effect.READ || c.effect() == Effect.UI);
            hints.put("destructiveHint", c.effect() == Effect.DESTRUCTIVE);
            t.put("annotations", hints);
            t.put("x-effect", c.effect().name().toLowerCase(java.util.Locale.ROOT));
            tools.put(t);
        }
        JSONObject m = new JSONObject();
        m.put("about", "Generated by CommandRegistry.main (docs/commands.md). Every HelioFITS Studio command, in the shape of an MCP tools list. Ids are API: never renamed.");
        m.put("tools", tools);
        return m;
    }

    /** Writes docs/commands.json to the file named by the one argument. Needs a display, as ActionCatalog.main does. */
    public static void main(String[] args) throws IOException {
        if (args.length != 1)
            throw new IllegalArgumentException("usage: CommandRegistry <output.json>");
        Platform.init();
        Files.writeString(Path.of(args[0]), manifest().toString(2) + "\n");
    }

    private CommandRegistry() {}
}
