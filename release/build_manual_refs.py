#!/usr/bin/env python3
"""The user manual's generated pages (DOCS-2): written from the files the app itself reads.

  build_manual_refs.py           write manual/generated/*.md
  build_manual_refs.py --check   exit 1 when a page would change, or a menu path in manual/*.md is not a real menu item

Sources, so the manual cannot drift from the app:
  docs/actions.md + docs/commands.json   -> generated/commands.md (every command, its menu and effect)
  resources/data/tours/*.json            -> generated/tours.md (the guided tours, step by step)
  resources/data/tips.json               -> generated/tips.md (Tip of the Day)
  changelog.md                           -> generated/history.md (with the [docs: ...] pointers dropped)

Menu paths in the hand-written chapters are written {menuselection}`Layers --> New PUNCH Layer...`;
each must be a menu path in docs/actions.md ("..." and the ellipsis character are the same here).
"""
import argparse
import glob
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "release"))
from docs_check import strip_pointers  # noqa: E402

GEN = os.path.join(ROOT, "manual", "generated")
HEADER = "<!-- Generated by release/build_manual_refs.py from {src}. Do not edit; edit the source. -->\n\n"
MENU_ROLE = re.compile(r"\{menuselection\}`([^`]+)`")


def read(rel):
    with open(os.path.join(ROOT, rel), encoding="utf-8") as f:
        return f.read()


def actions():
    """(id, menu path or "", description) rows from docs/actions.md, in its order."""
    rows = []
    for line in read("docs/actions.md").splitlines():
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) == 3 and cells[0].startswith("`") and cells[0].endswith("`"):
            menu = "" if cells[1] == "(none)" else cells[1]
            rows.append((cells[0].strip("`"), menu, cells[2]))
    return rows


def commands_page():
    effects = {t["name"]: t for t in json.loads(read("docs/commands.json"))["tools"]}
    out = [HEADER.format(src="docs/actions.md and docs/commands.json"), "# Commands\n\n",
           "Every command HelioFITS Studio has, as the menus, Help > Search Controls and the tours know it. "
           "Settings > Keybindings shows and changes the keyboard shortcut of each one. The id is the "
           "command's stable name in the command registry (docs/commands.md). A command marked "
           "*discards work* can throw away unsaved work or data.\n\n"]
    by_menu = {}
    for cid, menu, desc in actions():
        top = menu.split("/", 1)[0] if menu else "Not in a menu"
        by_menu.setdefault(top, []).append((cid, menu, desc))
    listed = set()

    def table(rows):
        lines = ["```{list-table}\n:header-rows: 1\n:widths: 40 40 20\n\n",
                 "* - Command\n  - What it does\n  - Id\n"]
        for name, desc, cid in rows:
            lines.append(f"* - {name}\n  - {desc}".rstrip() + f"\n  - `{cid}`\n")
        lines.append("```\n\n")
        return lines

    for top, rows in by_menu.items():
        out.append(f"## {top}\n\n")
        trows = []
        for cid, menu, desc in rows:
            listed.add(cid)
            label = menu.split("/")[-1] if menu else ""
            name = " > ".join(menu.split("/")) if menu else desc
            what = "" if (not menu or desc == label) else desc
            spec = effects.get(cid)
            if spec and spec["x-effect"] == "destructive":
                what = (what + " " if what else "") + "*(discards work)*"
            trows.append((name, what, cid))
        out += table(trows)
    extra = [t for name, t in effects.items() if name not in listed]
    if extra:
        out.append("## Commands that take arguments\n\nThese are run by scripts and Search Controls rather than "
                   "from a menu; the arguments are named after the description.\n\n")
        trows = []
        for t in extra:
            args = ", ".join(f"`{k}`" for k in t.get("inputSchema", {}).get("properties", {}))
            trows.append((t["description"], f"Arguments: {args}" if args else "No arguments", t["name"]))
        out += table(trows)
    return "".join(out)


def tours_page():
    order = ["getting-started", "loading-data", "making-a-movie", "views-and-projections",
             "rhef-and-filters", "sharing-your-work"]
    files = sorted(glob.glob(os.path.join(ROOT, "resources", "data", "tours", "*.json")),
                   key=lambda p: (order.index(os.path.basename(p)[:-5]) if os.path.basename(p)[:-5] in order
                                  else len(order), p))
    out = [HEADER.format(src="resources/data/tours/*.json"), "# Guided tours\n\n",
           "These are the app's own tours, written out. To take one in the app, with each control "
           "highlighted in turn, choose it under Help > Tours.\n\n"]
    for path in files:
        tour = json.load(open(path, encoding="utf-8"))
        out.append(f"## {tour['title']}\n\n")
        for i, step in enumerate(tour["steps"], 1):
            out.append(f"{i}. **{step['title']}.** {step['body']}\n")
        out.append("\n")
    return "".join(out)


def tips_page():
    tips = json.loads(read("resources/data/tips.json"))["tips"]
    out = [HEADER.format(src="resources/data/tips.json"), "# Tips\n\n",
           "The Tip of the Day collection (Help > Tip of the Day...), all on one page.\n\n"]
    for t in tips:
        out.append(f"**{t['title']}.** {t['text']}\n\n")
    return "".join(out)


def history_page():
    text = strip_pointers(read("changelog.md"))
    lines = text.splitlines()
    while lines and not lines[0].startswith("## "):
        lines.pop(0)  # the file's own title and notes; the page has its own
    body = "\n".join(lines)  # its "## " version headings sit under this page's "# " title as they are
    return HEADER.format(src="changelog.md") + "# Revision history\n\n" + body.strip() + "\n"


PAGES = {"commands.md": commands_page, "tours.md": tours_page, "tips.md": tips_page,
         "history.md": history_page}


def norm(path):
    return re.sub(r"\s+", " ", path.replace("…", "...").replace(" --> ", "/")).strip()


def menu_problems():
    known = {norm(menu) for _, menu, _ in actions() if menu}
    problems = []
    for path in sorted(glob.glob(os.path.join(ROOT, "manual", "*.md"))):
        for n, line in enumerate(open(path, encoding="utf-8"), 1):
            for m in MENU_ROLE.finditer(line):
                if norm(m.group(1)) not in known:
                    problems.append(f"{os.path.relpath(path, ROOT)}:{n}: not a menu item: {m.group(1)}")
    return problems


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    bad = menu_problems()
    for name, make in PAGES.items():
        path = os.path.join(GEN, name)
        new = make()
        old = open(path, encoding="utf-8").read() if os.path.exists(path) else None
        if old == new:
            continue
        if a.check:
            bad.append(f"manual/generated/{name} is out of date; run release/build_manual_refs.py")
        else:
            os.makedirs(GEN, exist_ok=True)
            with open(path, "w", encoding="utf-8") as f:
                f.write(new)
            print(f"wrote manual/generated/{name}")
    for b in bad:
        print(f"manual-refs: FAIL: {b}")
    if not bad:
        print("manual-refs: ok")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
